import { chromium, expect } from '../web/node_modules/@playwright/test/index.mjs';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const browser=await chromium.launch({channel:'msedge',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
try {
 const page=await browser.newPage({viewport:{width:1366,height:900}});
 const calls=[];const errors=[];
 page.on('request',request=>{if(new URL(request.url()).pathname.startsWith('/api/')) calls.push(request.url());});
 page.on('pageerror',error=>errors.push(error.message));
 await page.goto(process.env.NEXT_CHECK_URL || 'http://localhost:5173/');
 await page.waitForFunction(()=>/\d+ SPHEREx frames loaded\./.test(document.querySelector('.map-bottom')?.textContent || ''),null,{timeout:60000});
 const count=Number((await page.locator('.map-bottom').innerText()).match(/(\d+) SPHEREx frames loaded/)[1]);
 await expect.poll(()=>page.evaluate(async()=>{
   const cache=await caches.open('spherex-frontend-v1');
   return (await cache.keys()).filter(key=>key.url.includes('/api/frame.png')).length;
 }),{timeout:60000}).toBeGreaterThanOrEqual(count*2);
 const cold=calls.length;
 const coldCalls=[...calls];
 const cachedKeys=await page.evaluate(async()=>{const c=await caches.open('spherex-frontend-v1');return (await c.keys()).map(k=>k.url);});
 const duplicates=calls.filter(url=>url.includes('/api/frame.png') && new URL(url).searchParams.get('roll')==='0');
 assert.equal(new Set(duplicates).size,duplicates.length,'The engine downloaded a quick frame twice');
 calls.length=0;
 await page.reload();
 await page.waitForFunction(()=>/\d+ SPHEREx frames loaded\./.test(document.querySelector('.map-bottom')?.textContent || ''),null,{timeout:30000});
 await page.waitForTimeout(1000);
 if(calls.length) console.log(JSON.stringify({coldCalls,cachedKeys,afterReload:[...calls]}));
 assert.equal(calls.length,0,`Reload bypassed frontend cache: ${calls.join('\n')}`);
 console.log(JSON.stringify({coldApiRequests:cold,reloadApiRequests:calls.length}));
 await page.getByRole('button',{name:'Choose infrared bands',exact:true}).click();
 const panel=page.locator('#bands-panel');
 await expect(panel).toBeVisible();
 await expect(page.getByLabel('Search celestial objects')).toBeVisible();
 await expect.poll(async()=>{const b=await panel.boundingBox();return b.x+b.width;}).toBeLessThanOrEqual(1366);
 const bounds=await panel.boundingBox();assert(bounds.x>1366/2,'Sidebar is still centered');assert(bounds.x+bounds.width<=1366);
 await page.getByRole('tab',{name:/Detector 2/}).click();
 await page.getByRole('button',{name:'Select all 17 in Detector 2',exact:true}).click();
 await expect(page.locator('#bands-button-value')).toHaveText('18');
 await page.waitForResponse(response=>response.url().includes('/api/sequence') && new URL(response.url()).searchParams.get('detector')==='2',{timeout:30000});
 await page.getByRole('button',{name:'Select All 102 Bands',exact:true}).click();
 await expect(page.locator('#bands-button-value')).toHaveText('102');
 await page.getByRole('button',{name:'Deselect Detector 2',exact:true}).click();
 await expect(page.locator('#bands-button-value')).toHaveText('85');
 await page.getByRole('button',{name:'Close band selection',exact:true}).click();
 await page.getByRole('button',{name:'Open advanced options',exact:true}).click();
 await page.getByRole('button',{name:/Show Band A/}).click();
 await page.getByRole('button',{name:'Close advanced options',exact:true}).click();
 await page.getByRole('button',{name:'Choose infrared bands',exact:true}).click();
 await expect(page.locator('#bands-button-value')).toHaveText('1');
 const selected=page.getByRole('checkbox',{name:'Detector 2, local band 4, global band 21',exact:true});
 await expect(selected).toBeChecked();await selected.click();await expect(selected).toBeChecked();
 await expect(page.locator('#band-status')).toContainText('Keep at least one band');
 await mkdir('.cache/acceptance',{recursive:true});
 await panel.locator('.band-picker-large-view').evaluate(element=>element.scrollTop=0);
 await page.screenshot({path:'.cache/acceptance/bands-sidebar-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 const mobile=await panel.boundingBox();assert(mobile.x>=0 && mobile.x+mobile.width<=390 && mobile.y>=0 && mobile.y+mobile.height<=844);
 const sidebarOnTop=await panel.evaluate(element=>{
   const zoom=document.getElementById('zoom-in').getBoundingClientRect();
   return element.contains(document.elementFromPoint(zoom.x+zoom.width/2,zoom.y+zoom.height/2));
 });
 assert(sidebarOnTop,'Map controls overlap the mobile sidebar');
 await page.screenshot({path:'.cache/acceptance/bands-sidebar-mobile.png'});
 await page.getByRole('button',{name:'Close band selection',exact:true}).click();
 assert.deepEqual(errors,[]);
 console.log('PASS: frontend cache survives reload; detector/group/all-band selection, Advanced sync, last-band guard and floating desktop/mobile sidebar.');
} finally {await browser.close();}
